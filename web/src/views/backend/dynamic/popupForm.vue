<template>
    <!-- 对话框表单 -->
    <!-- 建议使用 Prettier 格式化代码 -->
    <!-- el-form 内可以混用 el-form-item、FormItem、ba-input 等输入组件 -->
    <el-dialog
        class="ba-operate-dialog"
        :close-on-click-modal="false"
        :model-value="['Add', 'Edit'].includes(baTable.form.operate!)"
        @close="baTable.toggleForm"
    >
        <template #header>
            <div class="title" v-drag="['.ba-operate-dialog', '.el-dialog__header']" v-zoom="'.ba-operate-dialog'">
                {{ baTable.form.operate ? t(baTable.form.operate) : '' }}
            </div>
        </template>
        <el-scrollbar v-loading="baTable.form.loading" class="ba-table-form-scrollbar">
            <div
                class="ba-operate-form"
                :class="'ba-' + baTable.form.operate + '-form'"
                :style="config.layout.shrink ? '':'width: calc(100% - ' + baTable.form.labelWidth! / 2 + 'px)'"
            >
                <el-form
                    v-if="!baTable.form.loading"
                    ref="formRef"
                    @submit.prevent=""
                    @keyup.enter="baTable.onSubmit(formRef)"
                    :model="baTable.form.items"
                    :label-position="config.layout.shrink ? 'top' : 'right'"
                    :label-width="baTable.form.labelWidth + 'px'"
                    :rules="rules"
                >
                    <FormItem :label="t('dynamic.openid')" type="remoteSelect" v-model="baTable.form.items!.openid" prop="openid" :input-attr="{ pk: 'account.openid', field: 'openid', remoteUrl: '/admin/Account/index' }" :placeholder="t('Please select field', { field: t('dynamic.openid') })" />
                    <FormItem :label="t('dynamic.text')" type="textarea" v-model="baTable.form.items!.text" prop="text" :input-attr="{ rows: 3 }" @keyup.enter.stop="" @keyup.ctrl.enter="baTable.onSubmit(formRef)" :placeholder="t('Please input field', { field: t('dynamic.text') })" />
                    <FormItem :label="t('dynamic.telephone')" type="textarea" v-model="baTable.form.items!.telephone" prop="telephone" :input-attr="{ rows: 3 }" @keyup.enter.stop="" @keyup.ctrl.enter="baTable.onSubmit(formRef)" :placeholder="t('Please input field', { field: t('dynamic.telephone') })" />
                    <FormItem :label="t('dynamic.area')" type="textarea" v-model="baTable.form.items!.area" prop="area" :input-attr="{ rows: 3 }" @keyup.enter.stop="" @keyup.ctrl.enter="baTable.onSubmit(formRef)" :placeholder="t('Please input field', { field: t('dynamic.area') })" />
                    <FormItem :label="t('dynamic.address')" type="textarea" v-model="baTable.form.items!.address" prop="address" :input-attr="{ rows: 3 }" @keyup.enter.stop="" @keyup.ctrl.enter="baTable.onSubmit(formRef)" :placeholder="t('Please input field', { field: t('dynamic.address') })" />
                    <FormItem :label="t('dynamic.lat')" type="string" v-model="baTable.form.items!.lat" prop="lat" :placeholder="t('Please input field', { field: t('dynamic.lat') })" />
                    <FormItem :label="t('dynamic.lng')" type="string" v-model="baTable.form.items!.lng" prop="lng" :placeholder="t('Please input field', { field: t('dynamic.lng') })" />
                </el-form>
            </div>
        </el-scrollbar>
        <template #footer>
            <div :style="'width: calc(100% - ' + baTable.form.labelWidth! / 1.8 + 'px)'">
                <el-button @click="baTable.toggleForm()">{{ t('Cancel') }}</el-button>
                <el-button v-blur :loading="baTable.form.submitLoading" @click="baTable.onSubmit(formRef)" type="primary">
                    {{ baTable.form.operateIds && baTable.form.operateIds.length > 1 ? t('Save and edit next item') : t('Save') }}
                </el-button>
            </div>
        </template>
    </el-dialog>
